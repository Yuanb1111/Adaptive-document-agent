"""Read sideways source text in its own orientation, retaining original extraction.

The same decoded glyph geometry supplies source tables and introductory reading.
Other orientations (including headers/footers) are retained separately; no text
is inferred from analytical labels or generated by a model.
"""
from collections import Counter
from math import atan2, degrees


def restore_rotated_reading(data, pdf, pages):
    import pymupdf
    candidates = []
    for native, page in zip(pdf, pages):
        geometry = native.get_text('dict', flags=pymupdf.TEXTFLAGS_DICT & ~pymupdf.TEXT_PRESERVE_IMAGES)
        directions = Counter()
        for block in geometry.get('blocks', []):
            for line in block.get('lines', []):
                x, y = line.get('dir', (1, 0))
                angle = round(degrees(atan2(y, x)) / 90) * 90 % 360
                directions[angle] += sum(len(span['text'].strip()) for span in line['spans'])
        if directions and directions.most_common(1)[0][0] != 0:
            candidates.append((page, directions))
    if not candidates:
        return
    import pypdfium2
    from .source_geometry import page_geometry
    from .ruled_source_tables import extract_ruled_source_tables
    from .table_extractor import TableExtractor
    decoded = pypdfium2.PdfDocument(data)
    try:
        for page, directions in candidates:
            native = decoded[page.page_number - 1]
            textpage = native.get_textpage()
            try:
                source = pdf[page.page_number - 1]
                passages = []
                for direction, _ in directions.most_common():
                    lines, _, turn = page_geometry(textpage, source, rotation=direction)
                    passages.extend(line.text for line in lines)
                if not passages:
                    continue
                page.raw_text = page.text
                page.text = '\n'.join(passages) + '\n'
                page.reading_rotation = (-directions.most_common(1)[0][0]) % 360
                tables, inventory = extract_ruled_source_tables(textpage, source, page.page_number)
                page.raw_tables = tables
                page.tables = [TableExtractor()._analytical_copy(table) for table in tables]
                page.source_table_inventory = inventory
            finally:
                textpage.close()
                native.close()
    finally:
        decoded.close()
